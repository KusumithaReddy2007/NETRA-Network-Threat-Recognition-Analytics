import {
  AlertCircle,
  Bell,
  Clock3,
  ShieldAlert,
} from "lucide-react";

function AlertsPage({ alerts }) {
  return (
    <div className="special-page">
      <div className="page-heading">
        <div>
          <div className="eyebrow">
            <span className="eyebrow-line" />
            SECURITY EVENTS
          </div>

          <h1>Alert Console</h1>

          <p>
            Standardized NETRA alerts generated by the
            threat detection engine.
          </p>
        </div>
      </div>

      <div className="alert-console-stats">
        <AlertMetric
          icon={Bell}
          label="TOTAL ALERTS"
          value={alerts.length}
        />

        <AlertMetric
          icon={ShieldAlert}
          label="CRITICAL"
          value={
            alerts.filter(
              (a) => a.severity === "CRITICAL"
            ).length
          }
          red
        />

        <AlertMetric
          icon={AlertCircle}
          label="HIGH"
          value={
            alerts.filter(
              (a) => a.severity === "HIGH"
            ).length
          }
        />

        <AlertMetric
          icon={Clock3}
          label="LATEST"
          value={
            alerts[0]
              ? formatTime(alerts[0].timestamp)
              : "--:--"
          }
        />
      </div>

      <div className="alert-console">
        {alerts.map((alert, index) => (
          <div
            className="console-alert"
            key={alert.alert_id || index}
          >
            <div
              className={`console-severity ${
                String(
                  alert.severity || "HIGH"
                ).toLowerCase()
              }`}
            />

            <div className="console-time">
              {formatTime(alert.timestamp)}
            </div>

            <div className="console-alert-main">
              <strong>{alert.threat_class}</strong>
              <span>{alert.alert_id}</span>
            </div>

            <div>
              <span className="console-label">
                IDENTIFIER
              </span>
              <strong className="mono">
                {alert.flow_id}
              </strong>
            </div>

            <div>
              <span className="console-label">
                CONFIDENCE
              </span>
              <strong className="confidence-cell">
                {alert.confidence}%
              </strong>
            </div>

            <div>
              <span className="console-label">
                SEVERITY
              </span>
              <strong>
                {alert.severity}
              </strong>
            </div>
          </div>
        ))}

        {!alerts.length && (
          <div className="console-empty">
            <Bell size={26} />
            <strong>No security alerts</strong>
            <span>Run traffic replay to generate events.</span>
          </div>
        )}
      </div>
    </div>
  );
}

function AlertMetric({
  icon: Icon,
  label,
  value,
  red,
}) {
  return (
    <div className={`alert-metric ${red ? "red" : ""}`}>
      <Icon size={18} />
      <span>{label}</span>
      <strong>{value}</strong>
    </div>
  );
}

function formatTime(timestamp) {
  if (!timestamp) return "--:--";

  try {
    return new Date(timestamp).toLocaleTimeString([], {
      hour12: false,
    });
  } catch {
    return "--:--";
  }
}

export default AlertsPage;
